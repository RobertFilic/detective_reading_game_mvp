// Case 6 (final): locked until 1–5 are solved; call → 🕐 timeline → scene → cross off → proof;
// ??? turns into Bip; the guess is checked on the solved screen and on the corkboard; letter.
import './brief-auto.mjs';
import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const ok = (c, m) => { console.log((c ? '✔ ' : '✘ ') + m); if (!c) process.exitCode = 1; };
const wait = (ms = 120) => new Promise(r => setTimeout(r, ms));
for (const [name, w, h, guess] of [['iphone14', 390, 844, 'alien'], ['ipad', 820, 1180, 'mouse'], ['land', 852, 393, null]]) {
  const p = await b.newPage();
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  await p.evaluateOnNewDocument(() => { if (window.speechSynthesis) speechSynthesis.getVoices = () => []; });
  await p.setViewport({ width: w, height: h, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  await p.goto('http://localhost:8765/solo/?play');
  await p.evaluate((guess) => { localStorage.clear(); localStorage.setItem('dp_save_version', '4'); localStorage.setItem('dp_tutorial_done', 'true');
    localStorage.setItem('dp_played_v1', JSON.stringify(['bip:1', 'bip:2', 'bip:3', 'bip:4']));
    if (guess) localStorage.setItem('dp_guess_v1', JSON.stringify({ bip: guess }));
    localStorage.setItem('dp_profile_v1', JSON.stringify({ av: '🕵🏽‍♀️', g: 'f', sk: '🐶', name: 'Ana', id: '1234' })); }, guess);
  await p.reload(); await wait(400);
  const text = () => p.evaluate(() => document.body.innerText);
  const st = () => p.evaluate(() => S.screen);
  const shot = (s) => p.screenshot({ path: `shots/b6-${name}-${s}.png` });
  const overflow = () => p.evaluate(() => { const W = document.documentElement.clientWidth; const bad = [];
    document.querySelectorAll('#app *').forEach(el => { if (el.closest('.pins')) return; const r = el.getBoundingClientRect(); if (r.width && (r.right > W + 1 || r.left < -1)) bad.push(el.className || el.tagName); });
    return [...new Set(bad)].slice(0, 6); });
  const inView = (sel) => p.$eval(sel, el => { const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight + 1; });
  const check = async (s) => { const o = await overflow(); ok(!o.length, `${name} ${s}: no overflow ${o.length ? JSON.stringify(o) : ''}`); await shot(s); };
  const slots = () => p.evaluate(() => S.run.slots.map(k => k === null ? '_' : k).join(''));
  const placeAll = async (order) => { for (const k of order) { await p.click(`.tcard[data-k="${k}"]`); await wait(40); } };
  await p.click('[data-act="openFile"][data-file="bip"]'); await wait();
  ok(await p.$('.folder.locked[data-no="6"]') && !(await p.$('.folder.soon')), `${name}: case 6 locked while 5 is open, nothing "coming"`);
  await p.evaluate(() => { localStorage.setItem('dp_played_v1', JSON.stringify(['bip:1', 'bip:2', 'bip:3', 'bip:4', 'bip:5'])); });
  await p.reload(); await wait(400);
  await p.click('[data-act="openFile"][data-file="bip"]'); await wait();
  ok((await text()).includes('Veliki primer') && !(await p.$('.folder.locked')), `${name}: case 6 open, "Veliki primer"`);
  await p.click('.folder[data-no="6"]'); await wait();
  await p.click('[data-act="answer"]'); await wait();
  ok((await text()).includes('modra luč') && (await p.$eval('[data-act="toScene"]', e => e.innerText)).includes('Poglej slike'), `${name}: Vesna calls, "Poglej slike 🕐"`);
  ok((await p.$$eval('.suspect span', els => els.map(e => e.innerText))).includes('???') && !(await text()).includes('Bip,'), `${name}: the 4th suspect is ??? (no Bip yet)`);
  await p.click('[data-act="toScene"]'); await wait();
  ok(await st() === 'order' && (await p.$$('.tdeck .tcard')).length === 4 && await p.$('[data-act="checkOrder"][disabled]'), `${name}: 4 mixed cards, »Preveri« off`);
  ok((await p.evaluate(() => S.run.deck.join(''))) !== '0123', `${name}: the cards are mixed`);
  await check('order');
  await placeAll([1, 0]);
  ok((await slots()) === '10__', `${name}: tapped cards fill slots 1 and 2`);
  await p.click('.tslot .tcard[data-i="0"]'); await wait();
  ok((await slots()) === '_0__' && (await p.$$('.tdeck .tcard')).length === 3, `${name}: tap a placed card → back to the cards`);
  await placeAll([3, 1, 2]);
  ok((await slots()) === '3012' && !(await p.$('.tdeck')) && await inView('[data-act="checkOrder"]:not([disabled])'), `${name}: all placed, »Preveri« on screen`);
  await check('order-full');
  await p.click('[data-act="checkOrder"]'); await wait();
  ok((await slots()) === '____' && (await text()).includes('Še ni prav') && !(await p.$('#hint')), `${name}: 1st wrong → all back, gentle note`);
  await placeAll([0, 2, 1, 3]); await p.click('[data-act="checkOrder"]'); await wait();
  ok((await slots()) === '0__3' && (await p.$$('.tslot.good')).length === 2, `${name}: right ones stay green`);
  ok((await p.$eval('#hint', e => e.innerText)).includes('Najprej, Potem'), `${name}: 2nd wrong → time words hint`);
  await p.click('[data-act="hintOk"]'); await wait();
  await placeAll([2, 1]); await p.click('[data-act="checkOrder"]'); await wait();
  ok((await p.$eval('#hint', e => e.innerText)).includes('Šele nato'), `${name}: 3rd wrong → "first bring the wire"`);
  await p.click('[data-act="hintOk"]'); await wait();
  await placeAll([2, 1]); await p.click('[data-act="checkOrder"]'); await wait();
  await p.click('[data-act="hintOk"]'); await wait();
  ok(await p.$('.tcard.pulse[data-k="1"]'), `${name}: 4th wrong → the next card pulses`);
  await placeAll([1, 2]); await p.click('[data-act="checkOrder"]'); await wait(300);
  ok(await p.evaluate(() => S.run.ordered) && (name === 'land' || (await text()).includes('naredil oddajnik')) && await p.$('[data-act="toScene"]'), `${name}: in order → "oddajnik", on to the scene`);
  ok(await inView('[data-act="toScene"]'), `${name}: "Na kraj dogodka" on screen`);
  await check('order-done');
  await p.click('[data-act="toScene"]'); await wait();
  ok(await st() === 'scene' && (await p.$$('.obj')).length === 7, `${name}: scene with 7 objects`);
  await p.click('[data-act="back"]'); await wait();
  ok(await st() === 'order' && await p.evaluate(() => S.run.ordered), `${name}: back → timeline stays done`);
  await p.click('[data-act="toScene"]'); await wait();
  await p.click('[data-act="torch"]'); await wait(60);
  for (const s of ['s1', 's2', 's3', 's4', 's5', 's6', 's7']) { await p.click(`.obj[data-sid="${s}"]`); await wait(60); }
  await p.click('[data-act="toSolve"]'); await wait();
  await p.click('[data-act="pickClue"][data-sid="s1"]'); await p.click('.suspect[data-id="robi"]'); await wait();
  ok(!!(await p.$('#hint')), `${name}: "Robi zna piskati" + Robi → hint`);
  await p.click('[data-act="hintOk"]'); await wait();
  for (const [sid, id] of [['s2', 'ela'], ['s4', 'kiki'], ['s6', 'robi']]) { await p.click(`[data-act="pickClue"][data-sid="${sid}"]`); await p.click(`.suspect[data-id="${id}"]`); await wait(80); }
  ok((await p.evaluate(() => S.run.crossed)).join() === 'ela,kiki,robi', `${name}: alibis cross off Ela, Kiki, Robi`);
  await check('solve');
  await p.click('[data-act="pickClue"][data-sid="s7"]'); await p.click('.suspect[data-id="bip"]'); await wait(2200);
  const t = await text();
  ok(t.includes('Detektivka Ana je ujela Bipa!') && (name === 'land' || await p.$('.unmask .real')), `${name}: "ujela Bipa!", ??? unmasked`);
  ok(t.includes('mali vesoljček') && (guess === 'alien' ? t.includes('Prav si ugibala') : guess ? t.includes('še ena miška') && t.includes('Nič hudega') : !t.includes('Tvoje ugibanje')), `${name}: the guess is checked (${guess})`);
  ok(await inView('[data-act="next"]'), `${name}: "Naprej" on screen`);
  await check('reveal');
  await p.click('[data-act="next"]'); await wait(1600);
  ok(name === 'land' || (await p.$$('.cork .pincard:not(.empty)')).length === 6 && !(await p.$('.cork .pincard.empty')), `${name}: all 6 cards pinned`);
  ok(name === 'land' || ((await p.$eval('.vent .eyes', e => e.innerText)) === '👾' && (await text()).includes('V zračniku je bil Bip')), `${name}: corkboard: 👾 in the vent and the answer`);
  ok(!(await p.$('.waiting')), `${name}: no "coming soon" note`);
  await shot('board');
  await p.reload(); await wait(400);
  await p.click('[data-act="openFile"][data-file="bip"]'); await wait();
  ok((await text()).includes('zeleno zvezdico'), `${name}: Vesna's letter`);
  const logs = await p.evaluate(() => JSON.stringify(LOG));
  ok(logs.includes('puzzle_order') && logs.includes('puzzle_done') && !logs.includes('"Ana"'), `${name}: timeline events logged, no name`);
  ok(errors.length === 0, `${name}: no page errors ${errors.join('|')}`);
  await p.close();
}
await b.close();
