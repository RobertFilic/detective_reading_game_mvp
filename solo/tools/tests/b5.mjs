// Case 5: call → 🔐 code lock (3-1-4 from case 4) → scene → cross off → proof; lock hints; back; letter.
import './brief-auto.mjs';
import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const ok = (c, m) => { console.log((c ? '✔ ' : '✘ ') + m); if (!c) process.exitCode = 1; };
const wait = (ms = 120) => new Promise(r => setTimeout(r, ms));
for (const [name, w, h] of [['iphone14', 390, 844], ['ipad', 820, 1180], ['land', 852, 393]]) {
  const p = await b.newPage();
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  await p.evaluateOnNewDocument(() => { if (window.speechSynthesis) speechSynthesis.getVoices = () => []; });
  await p.setViewport({ width: w, height: h, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  await p.goto('http://localhost:8765/solo/?play');
  await p.evaluate(() => { localStorage.clear(); localStorage.setItem('dp_save_version', '4'); localStorage.setItem('dp_tutorial_done', 'true');
    localStorage.setItem('dp_played_v1', JSON.stringify(['bip:1', 'bip:2', 'bip:3', 'bip:4']));
    localStorage.setItem('dp_profile_v1', JSON.stringify({ av: '🕵🏽‍♀️', g: 'f', sk: '🐶', name: 'Ana', id: '1234' })); });
  await p.reload(); await wait(400);
  const text = () => p.evaluate(() => document.body.innerText);
  const st = () => p.evaluate(() => S.screen);
  const shot = (s) => p.screenshot({ path: `shots/b5-${name}-${s}.png` });
  const overflow = () => p.evaluate(() => { const W = document.documentElement.clientWidth; const bad = [];
    document.querySelectorAll('#app *').forEach(el => { if (el.closest('.pins')) return; const r = el.getBoundingClientRect(); if (r.width && (r.right > W + 1 || r.left < -1)) bad.push(el.className || el.tagName); });
    return [...new Set(bad)].slice(0, 6); });
  const inView = (sel) => p.$eval(sel, el => { const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight + 1; });
  const check = async (s) => { const o = await overflow(); ok(!o.length, `${name} ${s}: no overflow ${o.length ? JSON.stringify(o) : ''}`); await shot(s); };
  const digits = () => p.$$eval('.digit', els => els.map(e => e.innerText).join(''));
  const turn = async (i, d, n) => { for (let k = 0; k < n; k++) { await p.click(`.wbtn[data-i="${i}"][data-d="${d}"]`); await wait(20); } };
  await p.click('.file-card[data-file="bip"]'); await wait();
  ok(!(await p.$('.folder.soon')) && await p.$('.folder[data-no="5"]:not(.locked)'), `${name}: board: case 5 open`);
  await p.click('.folder[data-no="5"]'); await wait();
  await p.click('[data-act="answer"]'); await wait();
  ok((await text()).includes('ključavnico s šifro') && (await p.$eval('[data-act="toScene"]', e => e.innerText)).includes('Naprej'), `${name}: Maja calls, »Naprej 👉«`);
  await p.click('[data-act="toScene"]'); await wait();
  ok(await st() === 'lock' && (await digits()) === '000' && !(await p.$('[data-act="toScene"]')), `${name}: lock 0-0-0, no way past it yet`);
  ok(await inView('[data-act="tryLock"]') && await inView('.wbtn[data-d="-1"]'), `${name}: wheels and »Odpri« on screen`);
  await check('lock');
  await turn(0, 1, 2); await turn(1, -1, 1);
  ok((await digits()) === '290', `${name}: ▲▼ turn the wheels (9 after 0)`);
  ok(await st() === 'lock' && !(await p.evaluate(() => S.run.open)), `${name}: no auto-check while turning`);
  await p.click('[data-act="tryLock"]'); await wait();
  ok((await text()).includes('se ne odpre') && !(await p.$('#hint')), `${name}: 1st wrong → gentle note`);
  await p.click('[data-act="tryLock"]'); await wait();
  ok((await p.$eval('#hint', e => e.innerText)).includes('listku v košu'), `${name}: 2nd wrong → "listek v košu"`);
  await p.click('[data-act="hintOk"]'); await wait();
  await p.click('[data-act="tryLock"]'); await wait(); await p.click('[data-act="tryLock"]'); await wait();
  ok((await p.$eval('#hint', e => e.innerText)).includes('3-1-4'), `${name}: 4th wrong → the code`);
  await p.click('[data-act="hintOk"]'); await wait();
  await turn(0, 1, 1); await turn(1, 1, 2); await turn(2, 1, 4);
  ok((await digits()) === '314', `${name}: wheels at 3-1-4`);
  await p.click('[data-act="tryLock"]'); await wait(500);
  ok(await p.$('.padlock.open') && (name === 'land' || (await text()).includes('Vrata so odprta')) && await p.$('[data-act="toScene"]'), `${name}: click! open, "Na kraj dogodka"`);
  ok(await inView("[data-act=\"toScene\"]"), `${name}: "Na kraj dogodka" on screen after opening`);
  await check("lock-open");
  await p.click('[data-act="toScene"]'); await wait();
  ok(await st() === 'scene' && (await p.$$('.obj')).length === 8, `${name}: scene with 8 objects`);
  await p.click('[data-act="back"]'); await wait();
  ok(await st() === 'lock' && await p.$('.padlock.open'), `${name}: back → lock stays open`);
  await p.click('[data-act="toScene"]'); await wait();
  await p.click('[data-act="torch"]'); await wait(60);
  for (const s of ['s1', 's2', 's3', 's4', 's5', 's6', 's7', 's8']) { await p.click(`.obj[data-sid="${s}"]`); await wait(60); }
  await check('scene');
  await p.click('[data-act="toSolve"]'); await wait();
  await p.click('[data-act="pickClue"][data-sid="s3"]'); await p.click('.suspect[data-id="robi"]'); await wait();
  ok(!!(await p.$('#hint')), `${name}: "Robi rad zbira vijake" + Robi → hint`);
  await p.click('[data-act="hintOk"]'); await wait();
  for (const [sid, id] of [['s2', 'kiki'], ['s4', 'ela'], ['s7', 'robi']]) { await p.click(`[data-act="pickClue"][data-sid="${sid}"]`); await p.click(`.suspect[data-id="${id}"]`); await wait(80); }
  ok((await p.evaluate(() => S.run.crossed)).join() === 'kiki,ela,robi', `${name}: alibis cross off Kiki, Ela, Robi`);
  await p.click('[data-act="pickClue"][data-sid="s6"]'); await p.click('.suspect[data-id="tim"]'); await wait(1600);
  ok((await text()).includes('Detektivka Ana je ujela Tima!'), `${name}: "Detektivka Ana je ujela Tima!"`);
  await check('reveal');
  await p.click('[data-act="next"]'); await wait();
  ok(name === 'land' || (await p.$$('.cork .pincard:not(.empty)')).length === 5, `${name}: 5 cards pinned`);
  ok(!(await p.$('.waiting')) && await p.$('.folder[data-no="6"]:not(.locked)'), `${name}: the final case 6 opens`);
  await wait(1500); await shot('board');
  await p.reload(); await wait(400);
  await p.click('.file-card[data-file="bip"]'); await wait();
  ok((await text()).includes('Iz zračnika spet piska'), `${name}: Maja's letter`);
  const logs = await p.evaluate(() => JSON.stringify(LOG));
  ok(logs.includes('puzzle_lock') && logs.includes('puzzle_done') && !logs.includes('"Ana"'), `${name}: lock events logged, no name`);
  ok(errors.length === 0, `${name}: no page errors ${errors.join('|')}`);
  await p.close();
}
await b.close();
