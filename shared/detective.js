  const solvedLabel = (n) => n % 100 === 1 ? `${n} rešena skrivnost` : n % 100 === 2 ? `${n} rešeni skrivnosti`
    : (n % 100 === 3 || n % 100 === 4) ? `${n} rešene skrivnosti` : `${n} rešenih skrivnosti`;
  // cases solved, counted without the main game's case list: the saved keys minus the old forest cases,
  // the only removed ones migrateSave() keeps (solo/ counts its own ALL_KEYS and should agree)
  const casesSolvedRough = (played = read('dp_played_v1', [])) => (Array.isArray(played) ? played : []).filter(k => typeof k === 'string' && !k.startsWith('gozd:')).length;

