  // ---- The device's own sittings (docs/marketing/ANALYTICS.md §3), kept on the device only (`dp_visits_v1`):
  // the sitting's number, the day of the first and of the last sitting, the last tap, the minutes in view in this
  // sitting, where the device first came from (a leaflet `?l=a07` or a link `?ref=…`, kept 60 days), and the start
  // page's A/B variant. A new sitting starts after 30 minutes without a tap. The server only ever gets numbers
  // worked out from these (`sittingData`), never the dates, and nothing that ties two sittings together.
  // »Kdo danes igra?«: asked in a sitting's first game screen, in the 1st sitting, then every 3rd (4th, 7th …).
  const VISITS = 'dp_visits_v1', GAP = 30 * 60 * 1000, DAY = 864e5;
  const days = (a, b) => Math.round((Date.parse(b) - Date.parse(a)) / DAY);
  let visit = null, isNew = false, prev = null, seen = null;
