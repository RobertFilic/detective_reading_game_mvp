  const points = (cases, rooms) => cases * GAME_POINTS.case + rooms * GAME_POINTS.room;
  const rankIndex = (pts) => RANKS.reduce((m, r, i) => (pts >= r.n ? i : m), 0);
  // the rank shown: the higher of the points' rank and the best one this detective ever reached (`rk` on the ID card)
  const rankOf = (p, pts) => RANKS[Math.max(rankIndex(pts), Math.min(RANKS.length - 1, (p && Number.isInteger(p.rk)) ? p.rk : 0))];
